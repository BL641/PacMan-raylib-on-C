void MapCopy() {
    for (int i = 0; i < MAP_LENGHT; i++) {
        for (int j = 0; j < MAP_HEIGHT; j++) {
            saveMap[i][j] = map[i][j];
            saveItemsMap[i][j] = itemsMap[i][j];
        }
    }
}

int MapRestore(){
    for (int i = 0; i < MAP_LENGHT; i++) {
        for (int j = 0; j < MAP_HEIGHT; j++) {
            map[i][j] = saveMap[i][j];
            itemsMap[i][j] = saveItemsMap[i][j];
        }
    }
    return 1;
}


int MapNull() {
    for (int i = 0; i < MAP_LENGHT; i++) {
        for (int j = 0; j < MAP_HEIGHT; j++) {
            map[i][j] = 0;
        }
    }

    return 0;
}


// Функция отрисовки карты
void MapDraw(PacMan* self) {
    if (self->round_delay > 0 && self->start == 0) {
        DrawText("READY!", 280, 480, 32, YELLOW);
    }

    DrawText(TextFormat("Score: %d", self->score), 10, 10, 30, WHITE);
    DrawText(TextFormat("Lv: %d", self->level), 10, 40, 30, WHITE);
    for (int y = 0; y < 28; y++) {
        for (int x = 0; x < 23; x++) {
            if (map[y][x] == 1) {
                DrawRectangle(x * 32, y * 32, 32, 32, DARKBLUE);
            }
            if (itemsMap[y][x] == 2) {
                DrawCircle(x * 32 + 16, y * 32 + 16, 3, RAYWHITE);
            }
        }
    }
}